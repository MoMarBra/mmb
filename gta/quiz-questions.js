function q(id, level, category, prompt, answer, others, explanation, source = null) {
  // Rotate the authoring order as well; A is not inherently the correct answer.
  const correct = (level + id.charCodeAt(id.length - 1)) % 4;
  const answers = [...others];
  answers.splice(correct, 0, answer);
  return Object.freeze({
    id,
    level,
    category,
    text: prompt,
    answers: Object.freeze(answers),
    correct,
    explanation,
    source,
  });
}

